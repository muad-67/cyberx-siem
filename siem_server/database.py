"""
database.py
SQLite database setup for the CyberX SIEM.
Creates all tables on first run; provides a shared get_db() helper.
"""

import sqlite3
import os
from config import Config


def get_db():
    """Open and return a database connection with dict-like row access."""
    conn = sqlite3.connect(Config.DB_PATH)
    conn.row_factory = sqlite3.Row   # lets us do row['column_name']
    conn.execute("PRAGMA journal_mode=WAL")  # better concurrency
    return conn


def init_db():
    """Create all tables and indexes. Called once at server startup."""
    conn = get_db()
    c = conn.cursor()

    # ── users ────────────────────────────────────────────────────────────
    # SOC analyst and admin accounts for dashboard authentication.
    c.execute("""
        CREATE TABLE IF NOT EXISTS users (
            id            INTEGER PRIMARY KEY AUTOINCREMENT,
            username      TEXT    NOT NULL UNIQUE,
            email         TEXT    NOT NULL UNIQUE,
            password_hash TEXT    NOT NULL,
            role          TEXT    NOT NULL DEFAULT 'analyst', -- admin | analyst
            is_active     INTEGER NOT NULL DEFAULT 1,
            created_at    DATETIME DEFAULT CURRENT_TIMESTAMP,
            last_login    DATETIME
        )
    """)

    # ── raw_logs ─────────────────────────────────────────────────────────
    # Every event received from an endpoint agent lands here first.
    c.execute("""
        CREATE TABLE IF NOT EXISTS raw_logs (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            timestamp   TEXT    NOT NULL,
            source_ip   TEXT    NOT NULL,
            hostname    TEXT    DEFAULT 'unknown',
            log_type    TEXT    NOT NULL,          -- auth | syslog | network | app | windows | web
            severity    TEXT    DEFAULT 'info',    -- info | low | medium | high | critical
            message     TEXT    NOT NULL,
            raw_data    TEXT,                      -- full JSON payload for forensics
            country     TEXT,                      -- geo enrichment
            city        TEXT,
            isp         TEXT,
            created_at  DATETIME DEFAULT CURRENT_TIMESTAMP
        )
    """)

    # ── alerts ───────────────────────────────────────────────────────────
    # Generated by the detection engine when a rule fires.
    c.execute("""
        CREATE TABLE IF NOT EXISTS alerts (
            id              INTEGER PRIMARY KEY AUTOINCREMENT,
            timestamp       TEXT    NOT NULL,
            alert_type      TEXT    NOT NULL,      -- brute_force | port_scan | ...
            severity        TEXT    NOT NULL,      -- low | medium | high | critical
            source_ip       TEXT,
            destination_ip  TEXT,
            description     TEXT,
            mitre_tactic    TEXT,                  -- e.g. Credential Access
            mitre_technique TEXT,                  -- e.g. T1110
            mitre_name      TEXT,                  -- e.g. Brute Force
            status          TEXT    DEFAULT 'open',-- open | investigating | resolved | false_positive
            log_ids         TEXT,                  -- comma-separated triggering log IDs
            risk_score      INTEGER DEFAULT 0,     -- 0-100 threat risk score
            created_at      DATETIME DEFAULT CURRENT_TIMESTAMP
        )
    """)

    # ── incidents ────────────────────────────────────────────────────────
    # Groups related alerts into a single investigation case.
    c.execute("""
        CREATE TABLE IF NOT EXISTS incidents (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            title       TEXT    NOT NULL,
            description TEXT,
            severity    TEXT    NOT NULL,
            status      TEXT    DEFAULT 'open',
            alert_ids   TEXT,
            assigned_to TEXT    DEFAULT 'SOC Analyst',
            tags        TEXT    DEFAULT '',         -- comma-separated tags
            priority    TEXT    DEFAULT 'medium',   -- low | medium | high | critical
            created_at  DATETIME DEFAULT CURRENT_TIMESTAMP,
            updated_at  DATETIME DEFAULT CURRENT_TIMESTAMP
        )
    """)

    # ── investigation_notes ──────────────────────────────────────────────
    # Analyst notes attached to an incident (audit trail).
    c.execute("""
        CREATE TABLE IF NOT EXISTS investigation_notes (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            incident_id INTEGER NOT NULL,
            author      TEXT    NOT NULL DEFAULT 'SOC Analyst',
            content     TEXT    NOT NULL,
            note_type   TEXT    DEFAULT 'note',   -- note | action | evidence | closure
            created_at  DATETIME DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (incident_id) REFERENCES incidents(id)
        )
    """)

    # ── blocked_ips ──────────────────────────────────────────────────────
    # Records simulated firewall block actions taken by the SOC analyst.
    c.execute("""
        CREATE TABLE IF NOT EXISTS blocked_ips (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            ip_address  TEXT    NOT NULL UNIQUE,
            reason      TEXT,
            blocked_by  TEXT    DEFAULT 'SOC Analyst',
            alert_id    INTEGER,
            created_at  DATETIME DEFAULT CURRENT_TIMESTAMP
        )
    """)

    # ── watchlist ────────────────────────────────────────────────────────
    # IPs flagged for heightened monitoring (boosts risk score).
    c.execute("""
        CREATE TABLE IF NOT EXISTS watchlist (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            ip_address  TEXT    NOT NULL UNIQUE,
            reason      TEXT,
            added_by    TEXT    DEFAULT 'SOC Analyst',
            created_at  DATETIME DEFAULT CURRENT_TIMESTAMP
        )
    """)

    # ── whitelist ────────────────────────────────────────────────────────
    # Trusted IPs that should never trigger alerts.
    c.execute("""
        CREATE TABLE IF NOT EXISTS whitelist (
            id          INTEGER PRIMARY KEY AUTOINCREMENT,
            ip_address  TEXT    NOT NULL UNIQUE,
            reason      TEXT,
            added_by    TEXT    DEFAULT 'SOC Analyst',
            created_at  DATETIME DEFAULT CURRENT_TIMESTAMP
        )
    """)

    # ── endpoints ────────────────────────────────────────────────────────
    # Tracks all machines that have sent logs (health monitoring).
    c.execute("""
        CREATE TABLE IF NOT EXISTS endpoints (
            id            INTEGER PRIMARY KEY AUTOINCREMENT,
            hostname      TEXT    NOT NULL UNIQUE,
            source_ip     TEXT,
            os_type       TEXT    DEFAULT 'unknown',
            agent_version TEXT    DEFAULT 'unknown',
            first_seen    DATETIME,
            last_seen     DATETIME,
            log_count     INTEGER DEFAULT 0,
            created_at    DATETIME DEFAULT CURRENT_TIMESTAMP
        )
    """)

    # ── threat_intel_cache ───────────────────────────────────────────────
    # Cached AbuseIPDB results — checked once per 24h per IP.
    c.execute("""
        CREATE TABLE IF NOT EXISTS threat_intel_cache (
            id            INTEGER PRIMARY KEY AUTOINCREMENT,
            ip_address    TEXT    NOT NULL UNIQUE,
            abuse_score   INTEGER DEFAULT 0,      -- 0-100
            is_malicious  INTEGER DEFAULT 0,      -- boolean
            isp           TEXT,
            usage_type    TEXT,
            total_reports INTEGER DEFAULT 0,
            country_code  TEXT,
            last_checked  DATETIME DEFAULT CURRENT_TIMESTAMP,
            source        TEXT    DEFAULT 'abuseipdb'
        )
    """)

    # ── Performance indexes ──────────────────────────────────────────────
    c.execute("CREATE INDEX IF NOT EXISTS idx_logs_ip       ON raw_logs(source_ip)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_logs_time     ON raw_logs(created_at)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_logs_type     ON raw_logs(log_type)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_alerts_ip     ON alerts(source_ip)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_alerts_type   ON alerts(alert_type)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_alerts_status ON alerts(status)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_users_username    ON users(username)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_endpoints_host    ON endpoints(hostname)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_endpoints_ip      ON endpoints(source_ip)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_notes_incident    ON investigation_notes(incident_id)")
    c.execute("CREATE INDEX IF NOT EXISTS idx_ti_ip             ON threat_intel_cache(ip_address)")

    conn.commit()
    conn.close()
    print("[DB] Schema initialized.")
    _migrate()


def _migrate():
    """Add columns that were introduced after the initial schema."""
    conn = get_db()
    c = conn.cursor()

    # Get current columns for each table
    def columns(table):
        return {row[1] for row in c.execute(f"PRAGMA table_info({table})")}

    alerts_cols   = columns("alerts")
    incidents_cols = columns("incidents")
    logs_cols     = columns("raw_logs")

    migrations = []

    if "risk_score" not in alerts_cols:
        c.execute("ALTER TABLE alerts ADD COLUMN risk_score INTEGER DEFAULT 0")
        migrations.append("alerts.risk_score")

    if "mitre_tactic" not in alerts_cols:
        c.execute("ALTER TABLE alerts ADD COLUMN mitre_tactic TEXT")
        migrations.append("alerts.mitre_tactic")

    if "mitre_technique" not in alerts_cols:
        c.execute("ALTER TABLE alerts ADD COLUMN mitre_technique TEXT")
        migrations.append("alerts.mitre_technique")

    if "mitre_name" not in alerts_cols:
        c.execute("ALTER TABLE alerts ADD COLUMN mitre_name TEXT")
        migrations.append("alerts.mitre_name")

    if "destination_ip" not in alerts_cols:
        c.execute("ALTER TABLE alerts ADD COLUMN destination_ip TEXT")
        migrations.append("alerts.destination_ip")

    if "log_ids" not in alerts_cols:
        c.execute("ALTER TABLE alerts ADD COLUMN log_ids TEXT")
        migrations.append("alerts.log_ids")

    if "tags" not in incidents_cols:
        c.execute("ALTER TABLE incidents ADD COLUMN tags TEXT DEFAULT ''")
        migrations.append("incidents.tags")

    if "priority" not in incidents_cols:
        c.execute("ALTER TABLE incidents ADD COLUMN priority TEXT DEFAULT 'medium'")
        migrations.append("incidents.priority")

    if "country" not in logs_cols:
        c.execute("ALTER TABLE raw_logs ADD COLUMN country TEXT")
        migrations.append("raw_logs.country")

    if "city" not in logs_cols:
        c.execute("ALTER TABLE raw_logs ADD COLUMN city TEXT")
        migrations.append("raw_logs.city")

    if "isp" not in logs_cols:
        c.execute("ALTER TABLE raw_logs ADD COLUMN isp TEXT")
        migrations.append("raw_logs.isp")

    conn.commit()
    conn.close()

    if migrations:
        print(f"[DB] Migrated columns: {', '.join(migrations)}")
    else:
        print("[DB] Schema up to date.")


def seed_default_users():
    """Create default admin and analyst accounts if they don't already exist."""
    import hashlib, os

    def _hash(password: str) -> str:
        salt = os.urandom(16).hex()
        hashed = hashlib.sha256((salt + password).encode()).hexdigest()
        return f"{salt}:{hashed}"

    defaults = [
        ("mohadek", "mohadek@cyberx.local", "mohadek123", "admin"),
        ("sabrin",  "sabrin@cyberx.local",  "mohadek123", "analyst"),
    ]

    conn = get_db()
    created = []
    for username, email, password, role in defaults:
        exists = conn.execute(
            "SELECT id FROM users WHERE username = ?", (username,)
        ).fetchone()
        if not exists:
            conn.execute(
                "INSERT INTO users (username, email, password_hash, role) VALUES (?, ?, ?, ?)",
                (username, email, _hash(password), role),
            )
            created.append(f"{username} ({role})")
    conn.commit()
    conn.close()

    if created:
        print(f"[DB] Default users created: {', '.join(created)}")
    else:
        print("[DB] Default users already exist.")
